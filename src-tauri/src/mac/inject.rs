//! Text insertion on macOS: snapshot the pasteboard, put our text on it, post Command+V, then
//! restore the user's pasteboard unless they copied something new (checked via `changeCount`).
//!
//! Our transient item carries the nspasteboard.org markers so clipboard managers skip it.
//! Posting keystrokes needs Accessibility permission (see `hotkey::request_permission`).

use std::time::Duration;

use core_graphics::event::{CGEvent, CGEventFlags, CGEventTapLocation};
use core_graphics::event_source::{CGEventSource, CGEventSourceStateID};
use objc2::rc::Retained;
use objc2::runtime::ProtocolObject;
use objc2_app_kit::{NSPasteboard, NSPasteboardItem, NSPasteboardTypeString, NSPasteboardWriting};
use objc2_foundation::{NSArray, NSData, NSString};
use voxora_core::context::PasteKeys;

const TRANSIENT_TYPES: &[&str] =
    &["org.nspasteboard.TransientType", "org.nspasteboard.ConcealedType", "org.nspasteboard.AutoGeneratedType"];
const KEY_V: u16 = 9;
/// Skip absurdly large items (a copied video) instead of stalling the paste.
const MAX_SNAPSHOT_BYTES: usize = 64 * 1024 * 1024;

/// Every item on the pasteboard, as (type, bytes) pairs.
pub struct Snapshot(Vec<Vec<(String, Vec<u8>)>>);

pub fn snapshot() -> Result<Snapshot, String> {
    let pb = NSPasteboard::generalPasteboard();
    let mut items = Vec::new();
    let mut total = 0usize;
    for item in pb.pasteboardItems().map(|a| a.to_vec()).unwrap_or_default() {
        let mut kinds = Vec::new();
        for ty in item.types().to_vec() {
            if let Some(data) = item.dataForType(&ty) {
                let bytes = data.to_vec();
                total += bytes.len();
                if total > MAX_SNAPSHOT_BYTES {
                    return Err("clipboard too large to snapshot".into());
                }
                kinds.push((ty.to_string(), bytes));
            }
        }
        items.push(kinds);
    }
    Ok(Snapshot(items))
}

fn write_items(items: Vec<Retained<NSPasteboardItem>>) -> Result<isize, String> {
    let pb = NSPasteboard::generalPasteboard();
    pb.clearContents();
    let objs: Vec<Retained<ProtocolObject<dyn NSPasteboardWriting>>> =
        items.into_iter().map(ProtocolObject::from_retained).collect();
    if !pb.writeObjects(&NSArray::from_retained_slice(&objs)) {
        return Err("pasteboard write failed".into());
    }
    Ok(pb.changeCount())
}

fn restore(s: &Snapshot) -> Result<(), String> {
    let items =
        s.0.iter()
            .map(|kinds| {
                let item = NSPasteboardItem::new();
                for (ty, bytes) in kinds {
                    item.setData_forType(&NSData::with_bytes(bytes), &NSString::from_str(ty));
                }
                item
            })
            .collect();
    write_items(items).map(|_| ())
}

/// Put `text` on the pasteboard. `transient` hides it from clipboard managers.
/// Returns the pasteboard change count after the write.
pub fn set_text(text: &str, transient: bool) -> Result<u32, String> {
    let item = NSPasteboardItem::new();
    item.setString_forType(&NSString::from_str(text), unsafe { NSPasteboardTypeString });
    if transient {
        for ty in TRANSIENT_TYPES {
            item.setData_forType(&NSData::with_bytes(&[]), &NSString::from_str(ty));
        }
    }
    write_items(vec![item]).map(|c| c as u32)
}

fn send_paste() -> Result<(), String> {
    let source = || CGEventSource::new(CGEventSourceStateID::HIDSystemState).map_err(|_| "no event source".to_string());
    let down = CGEvent::new_keyboard_event(source()?, KEY_V, true).map_err(|_| "key event failed")?;
    let up = CGEvent::new_keyboard_event(source()?, KEY_V, false).map_err(|_| "key event failed")?;
    // Command only: a still-held Option would turn this into Option+Command+V ("move" in Finder).
    down.set_flags(CGEventFlags::CGEventFlagCommand);
    up.set_flags(CGEventFlags::CGEventFlagCommand);
    down.post(CGEventTapLocation::HID);
    std::thread::sleep(Duration::from_millis(8));
    up.post(CGEventTapLocation::HID);
    Ok(())
}

pub struct PasteOptions {
    /// Windows-only choice (Ctrl+V / Ctrl+Shift+V / Shift+Insert); macOS always uses Command+V.
    #[allow(dead_code)]
    pub keys: PasteKeys,
    pub restore_clipboard: bool,
    pub restore_delay_ms: u64,
}

/// Paste `text` into the focused app. On error the text is still on the pasteboard.
pub fn paste(text: &str, opts: &PasteOptions) -> Result<(), String> {
    let saved = if opts.restore_clipboard { snapshot().ok() } else { None };
    let seq = set_text(text, opts.restore_clipboard)?;
    std::thread::sleep(Duration::from_millis(20)); // let the pasteboard server settle
    send_paste()?;
    if let Some(saved) = saved {
        let delay = opts.restore_delay_ms;
        std::thread::spawn(move || {
            std::thread::sleep(Duration::from_millis(delay));
            if NSPasteboard::generalPasteboard().changeCount() as u32 == seq
                && let Err(e) = restore(&saved)
            {
                tracing::warn!("clipboard restore failed: {e}");
            }
        });
    }
    Ok(())
}
